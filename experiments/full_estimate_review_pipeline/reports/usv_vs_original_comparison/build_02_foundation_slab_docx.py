def format_qty(value: float, unit: str) -> str:
    """Excel-style fixed 2-decimal, comma-separator display, NO thousands separator - confirmed
    against the real smeta screenshot ("6399,90", "8627,10", not "6 399,90"): 222.3 -> '222,30 мп'.
    Uses Decimal(str(value)) + ROUND_HALF_UP, not raw float f"{value:.2f}" - plain float formatting
    silently rounds DOWN on values whose binary float representation sits just under the true
    decimal (39.555 -> "39.55" instead of the correct "39.56") - caught by the walls-section
    J-column verification (2026-08-26)."""
    quantized = Decimal(str(value)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
    return str(quantized).replace(".", ",") + f" {unit}"


